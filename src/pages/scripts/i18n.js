const flagSources = {
  ar: "https://flagcdn.com/w80/sa.png",
  en: "https://flagcdn.com/w80/gb.png"
};

function setLanguage(lang) {
  const selected = translations[lang] ? lang : "ar";
  const dictionary = translations[selected];

  document.documentElement.lang = selected;
  document.documentElement.dir = selected === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });

  const currentFlag = document.getElementById("current-flag");
  if (currentFlag) {
    currentFlag.src = flagSources[selected];
    currentFlag.alt = selected === "ar" ? "علم المملكة العربية السعودية" : "Flag of the United Kingdom";
  }

  document.querySelectorAll("[data-language]").forEach((button) => {
    const isActive = button.dataset.language === selected;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  try {
    localStorage.setItem("site-language", selected);
  } catch (error) {
    console.warn("Could not save the selected language.", error);
  }
}

function initializeLanguageSwitcher() {
  const languageMenu = document.getElementById("language-menu");
  const languageToggle = document.querySelector(".language-toggle");
  const languageOptions = document.getElementById("language-options");

  if (languageToggle && languageOptions) {
    languageToggle.addEventListener("click", (event) => {
      event.stopPropagation();
      const isOpen = languageOptions.classList.toggle("show");
      languageToggle.setAttribute("aria-expanded", String(isOpen));
    });

    languageOptions.querySelectorAll("[data-language]").forEach((button) => {
      button.addEventListener("click", (event) => {
        event.stopPropagation();
        setLanguage(button.dataset.language);
        languageOptions.classList.remove("show");
        languageToggle.setAttribute("aria-expanded", "false");
      });
    });

    document.addEventListener("click", (event) => {
      if (languageMenu && !languageMenu.contains(event.target)) {
        languageOptions.classList.remove("show");
        languageToggle.setAttribute("aria-expanded", "false");
      }
    });
  }

  let savedLanguage = "ar";
  try {
    savedLanguage = localStorage.getItem("site-language") || "ar";
  } catch (error) {
    console.warn("Could not read the saved language.", error);
  }
  setLanguage(savedLanguage);
}

if (typeof document !== "undefined") {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initializeLanguageSwitcher, { once: true });
  } else {
    initializeLanguageSwitcher();
  }
}
